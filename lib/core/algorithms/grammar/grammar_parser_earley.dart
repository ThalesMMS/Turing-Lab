class _EarleyState {
  final String lhs;
  final List<String> rhs;
  final int dot;
  final int origin;

  const _EarleyState(this.lhs, this.rhs, this.dot, this.origin);

  bool get complete => dot >= rhs.length;
  String? get nextSym => complete ? null : rhs[dot];

  @override
  bool operator ==(Object other) {
    if (identical(this, other)) return true;
    if (other is! _EarleyState) return false;
    if (lhs != other.lhs || dot != other.dot || origin != other.origin) {
      return false;
    }
    final a = rhs, b = other.rhs;
    if (a.length != b.length) return false;
    for (var i = 0; i < a.length; i++) {
      if (a[i] != b[i]) return false;
    }
    return true;
  }

  @override
  int get hashCode {
    var h = lhs.hashCode ^ dot.hashCode ^ origin.hashCode;
    for (final s in rhs) {
      h = 0x1fffffff & (h + s.hashCode);
      h = 0x1fffffff & (h + ((0x0007ffff & h) << 10));
      h ^= (h >> 6);
    }
    return h;
  }
}

class EarleyRecognizer {
  final Grammar grammar;
  late final Map<String, List<List<String>>> _rules;
  late final Set<String> _nonterminals;
  late final Set<String> _terminals;
  String? _malformedGrammarMessage;
  StructuredMessage? _malformedGrammarStructuredMessage;

  EarleyRecognizer(this.grammar) {
    _nonterminals = grammar.nonterminals;
    _terminals = grammar.terminals;

    _rules = {};
    for (final p in grammar.productions) {
      if (p.leftSide.length != 1 ||
          !_nonterminals.contains(p.leftSide.single)) {
        _malformedGrammarMessage ??=
            'Earley requires productions with one declared nonterminal LHS.';
        _malformedGrammarStructuredMessage ??=
            GrammarParserMessages.earleyMalformedProduction();
        continue;
      }
      final lhs = p.leftSide.single;
      final rhs = (p.isLambda || p.rightSide.isEmpty)
          ? <String>[]
          : List<String>.from(p.rightSide);
      (_rules[lhs] ??= <List<String>>[]).add(rhs);
    }
  }

  bool _isNonTerminal(String s) => _nonterminals.contains(s);

  /// Recognize whether [input] is generated by [grammar].
  ///
  /// Returns `false` on rejection, timeouts, or malformed grammars (best-effort).
  bool recognizes(
    String input, {
    Duration timeout = const Duration(seconds: 5),
  }) {
    final report = recognizeWithReport(input, timeout: timeout);
    return report.accepted;
  }

  /// Runs Earley recognition and returns structured feedback.
  ///
  /// This is best-effort and non-throwing: on timeout it returns a rejected
  /// report with an explanatory message.
  GrammarParseReport recognizeWithReport(
    String input, {
    Duration timeout = const Duration(seconds: 5),
  }) {
    final startTime = DateTime.now();
    if (_malformedGrammarMessage != null ||
        !grammar.nonterminals.contains(grammar.startSymbol)) {
      final structuredMessage =
          _malformedGrammarStructuredMessage ??
          GrammarParserMessages.earleyMissingStartSymbol();
      return GrammarParseReport.rejected(
        inputString: input,
        farthestPosition: 0,
        message:
            _malformedGrammarMessage ??
            'Earley requires a declared nonterminal start symbol.',
        executionTime: DateTime.now().difference(startTime),
        structuredMessage: structuredMessage,
        outcome: GrammarParseOutcome.invalidInput,
      );
    }
    if (timeout <= Duration.zero) {
      final structuredMessage = GrammarParserMessages.earleyTimedOut(timeout);
      return GrammarParseReport.rejected(
        inputString: input,
        farthestPosition: 0,
        message: 'Parse timed out after ${timeout.inMilliseconds}ms',
        executionTime: DateTime.now().difference(startTime),
        structuredMessage: structuredMessage,
        outcome: GrammarParseOutcome.timedOut,
      );
    }
    final tokenResult = GrammarInputTokenizer.tokenize(grammar, input);
    if (tokenResult.isFailure) {
      return GrammarParseReport.rejected(
        inputString: input,
        farthestPosition: 0,
        message: tokenResult.error,
        structuredMessage: tokenResult.structuredError,
        executionTime: DateTime.now().difference(startTime),
        outcome: GrammarParseOutcome.tokenizationFailure,
      );
    }
    final tokens = tokenResult.data!;

    int rawPosition(int tokenPosition) => tokenPosition >= tokens.length
        ? input.length
        : tokens[tokenPosition].start;

    final String start = grammar.startSymbol;
    // Augment start S' -> S with a unique name
    String startPrime = start;
    do {
      startPrime = '\u0000$startPrime\u0000';
    } while (_nonterminals.contains(startPrime) ||
        _terminals.contains(startPrime));

    final int n = tokens.length;
    final List<Set<_EarleyState>> chart = List.generate(
      n + 1,
      (_) => <_EarleyState>{},
    );

    bool timedOut() => DateTime.now().difference(startTime) > timeout;

    bool addState(Set<_EarleyState> set, _EarleyState s) {
      if (timedOut()) return false;
      return set.add(s);
    }

    // Expected terminals at each position (best-effort).
    final List<Set<String>> expected = List.generate(n + 1, (_) => <String>{});

    void recordExpectedTerminal(int position, String terminal) {
      if (position < 0 || position > n) return;
      expected[position].add(terminal);
    }

    // Seed
    addState(chart[0], _EarleyState(startPrime, [start], 0, 0));

    int farthestTokenPosition = 0;

    for (int i = 0; i <= n; i++) {
      bool changed;
      do {
        changed = false;
        final current = List<_EarleyState>.from(chart[i]);

        for (final state in current) {
          if (timedOut()) {
            final structuredMessage = GrammarParserMessages.earleyTimedOut(
              timeout,
            );
            return GrammarParseReport.rejected(
              inputString: input,
              farthestPosition: rawPosition(farthestTokenPosition),
              expectedSymbols: expected[farthestTokenPosition],
              message: 'Parse timed out after ${timeout.inMilliseconds}ms',
              executionTime: DateTime.now().difference(startTime),
              structuredMessage: structuredMessage,
              outcome: GrammarParseOutcome.timedOut,
            );
          }

          if (state.complete) {
            // Completer
            final prevSnapshot = List<_EarleyState>.from(chart[state.origin]);
            for (final prev in prevSnapshot) {
              final exp = prev.nextSym;
              if (exp != null && exp == state.lhs) {
                final advanced = _EarleyState(
                  prev.lhs,
                  prev.rhs,
                  prev.dot + 1,
                  prev.origin,
                );
                if (addState(chart[i], advanced)) changed = true;
              }
            }
          } else {
            final sym = state.nextSym!;
            if (_isNonTerminal(sym)) {
              // Predictor
              final alts = _rules[sym] ?? const <List<String>>[];
              if (alts.isEmpty) {
                continue;
              }
              for (final rhs in alts) {
                final predicted = _EarleyState(sym, rhs, 0, i);
                if (addState(chart[i], predicted)) changed = true;
              }
            } else {
              // Scanner
              recordExpectedTerminal(i, sym);
              if (i < n && tokens[i].lexeme == sym) {
                final nextIdx = i + 1;
                if (nextIdx > farthestTokenPosition) {
                  farthestTokenPosition = nextIdx;
                }
                final advanced = _EarleyState(
                  state.lhs,
                  state.rhs,
                  state.dot + 1,
                  state.origin,
                );
                addState(chart[nextIdx], advanced);
              }
            }
          }
        }
      } while (changed);

      if (timedOut()) {
        final structuredMessage = GrammarParserMessages.earleyTimedOut(timeout);
        return GrammarParseReport.rejected(
          inputString: input,
          farthestPosition: rawPosition(farthestTokenPosition),
          expectedSymbols: expected[farthestTokenPosition],
          message: 'Parse timed out after ${timeout.inMilliseconds}ms',
          executionTime: DateTime.now().difference(startTime),
          structuredMessage: structuredMessage,
          outcome: GrammarParseOutcome.timedOut,
        );
      }
    }

    final accepted = chart[n].contains(_EarleyState(startPrime, [start], 1, 0));
    final elapsed = DateTime.now().difference(startTime);

    if (accepted) {
      return GrammarParseReport.accepted(
        inputString: input,
        executionTime: elapsed,
      );
    }

    // Rejected: use best-effort farthest position and expected terminals.
    final structuredMessage = GrammarParserMessages.inputRejected(input);
    return GrammarParseReport.rejected(
      inputString: input,
      farthestPosition: rawPosition(farthestTokenPosition),
      expectedSymbols: expected[farthestTokenPosition],
      message: 'String "$input" cannot be derived from grammar',
      executionTime: elapsed,
      structuredMessage: structuredMessage,
    );
  }
}
